#!/usr/bin/env python3
"""Build the root app_process helper in a disposable Docker build container."""
from pathlib import Path
import base64
import datetime
import hashlib
import json
import os
import shutil
import subprocess
import uuid
import zipfile

if not Path("/.dockerenv").exists():
    raise SystemExit("Android helper builds must run inside a disposable Docker container")
root = Path(__file__).resolve().parents[2]
sdk = Path(os.environ.get("ANDROID_SDK_ROOT", "/opt/android-sdk"))
java = Path(os.environ.get("JAVA_HOME", "/opt/java-17-openjdk-amd64"))
android_jar = sdk / "platforms/android-35/android.jar"
build_tools = sdk / "build-tools/35.0.0"
stamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%dT%H%M%SZ") + "-" + uuid.uuid4().hex[:8]
output = root / ".tmp/android-workspace-build" / stamp
classes = output / "classes"
dex = output / "dex"
classes.mkdir(parents=True)
dex.mkdir()
sources = sorted((root / "packages/android-workspace/src").rglob("*.java"))
environment = {**os.environ, "JAVA_HOME": str(java), "PATH": str(java / "bin") + ":" + os.environ["PATH"]}
subprocess.run([str(java / "bin/javac"), "--release", "8", "-encoding", "UTF-8", "-classpath", str(android_jar), "-d", str(classes), *map(str, sources)], check=True, env=environment)
subprocess.run([str(build_tools / "d8"), "--min-api", "34", "--lib", str(android_jar), "--output", str(dex), *map(str, sorted(classes.rglob("*.class")))], check=True, env=environment)
artifact = output / "relay-android-workspace.jar"
with zipfile.ZipFile(artifact, "w", compression=zipfile.ZIP_DEFLATED) as bundle:
    for file in sorted(dex.glob("*.dex")):
        info = zipfile.ZipInfo(file.name, (2026, 1, 1, 0, 0, 0))
        info.compress_type = zipfile.ZIP_DEFLATED
        bundle.writestr(info, file.read_bytes())
data = artifact.read_bytes()
digest = hashlib.sha256(data).hexdigest()
generated = root / "packages/device/src/computer/android-workspace.generated.ts"
if generated.exists():
    shutil.copy2(generated, output / "previous.generated.ts")
generated.write_text("// Generated by packages/android-workspace/build.py; Android 14+ app_process helper.\n"
    + "export const ANDROID_WORKSPACE_HELPER = " + json.dumps({"version": 1, "sha256": digest, "base64": base64.b64encode(data).decode("ascii")}, separators=(",", ":")) + " as const;\n")
print(json.dumps({"artifact": str(artifact), "sha256": digest, "bytes": len(data), "generated": str(generated)}))
# The probe APK is test-only and is never embedded in the device bundle.
if "--probe" in __import__("sys").argv:
    probe_root = root / "packages/android-workspace/probe"
    probe_classes = output / "probe-classes"
    probe_dex = output / "probe-dex"
    probe_classes.mkdir()
    probe_dex.mkdir()
    subprocess.run([str(java / "bin/javac"), "--release", "8", "-encoding", "UTF-8", "-classpath", str(android_jar), "-d", str(probe_classes), *map(str, sorted((probe_root / "src").rglob("*.java")))], check=True, env=environment)
    subprocess.run([str(build_tools / "d8"), "--min-api", "34", "--lib", str(android_jar), "--output", str(probe_dex), *map(str, sorted(probe_classes.rglob("*.class")))], check=True, env=environment)
    unsigned = output / "probe-unsigned.apk"
    subprocess.run([str(build_tools / "aapt2"), "link", "-I", str(android_jar), "--manifest", str(probe_root / "AndroidManifest.xml"), "-o", str(unsigned)], check=True, env=environment)
    with zipfile.ZipFile(unsigned, "a", compression=zipfile.ZIP_DEFLATED) as apk:
        apk.write(probe_dex / "classes.dex", "classes.dex")
    aligned = output / "probe-aligned.apk"
    subprocess.run([str(build_tools / "zipalign"), "-f", "4", str(unsigned), str(aligned)], check=True)
    keystore = output / "probe-test-only.p12"
    subprocess.run([str(java / "bin/keytool"), "-genkeypair", "-keystore", str(keystore), "-storetype", "PKCS12", "-alias", "probe", "-storepass", "android", "-keypass", "android", "-keyalg", "RSA", "-keysize", "2048", "-validity", "2", "-dname", "CN=Relay Test Only"], check=True, env=environment, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    probe_apk = output / "relay-workspace-probe.apk"
    subprocess.run([str(build_tools / "apksigner"), "sign", "--ks", str(keystore), "--ks-key-alias", "probe", "--ks-pass", "pass:android", "--out", str(probe_apk), str(aligned)], check=True, env=environment)
    print(json.dumps({"probeArtifact": str(probe_apk), "sha256": hashlib.sha256(probe_apk.read_bytes()).hexdigest(), "bytes": probe_apk.stat().st_size}))

